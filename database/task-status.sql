-- One-time normalization of legacy string statuses before restarting with TaskStatus.
ALTER TABLE tasks MODIFY COLUMN status VARCHAR(255) NOT NULL DEFAULT 'PENDING';
UPDATE tasks SET status = CASE UPPER(TRIM(status))
    WHEN 'COMPLETED' THEN 'COMPLETED'
    WHEN 'COMPLTED' THEN 'COMPLETED'
    WHEN 'DONE' THEN 'COMPLETED'
    WHEN 'POSTPONED' THEN 'POSTPONED'
    ELSE 'PENDING'
END;
ALTER TABLE tasks MODIFY COLUMN status ENUM('PENDING', 'POSTPONED', 'COMPLETED') NOT NULL DEFAULT 'PENDING';
